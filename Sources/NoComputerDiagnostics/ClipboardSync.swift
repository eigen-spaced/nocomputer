import AppKit

struct ClipboardSnapshot {
    var sent = 0
    var applied = 0
    var skippedSecret = 0
    var skippedLarge = 0
    var skippedNonText = 0
}

// Plain-text clipboard sharing with the controlling viewer. macOS has no change
// notification, so the change count is polled while a session runs. Text lives in
// memory only, to recognise its own echo; it is never logged or saved.
@MainActor
final class ClipboardSync {
    static let pollInterval: TimeInterval = 0.25
    // Markers password managers and similar apps set (nspasteboard.org). Checking
    // them reads only the type list, never the data.
    static let secretTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType")
    ]

    var onLocalText: ((LocalLink.ClipboardText) -> Void)?
    private(set) var state = ClipboardSnapshot()
    private let pasteboard: NSPasteboard
    private var seenChangeCount: Int
    private var lastText: String?
    private var timer: Timer?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        seenChangeCount = pasteboard.changeCount
    }

    var running: Bool { timer != nil }

    // Only later changes are sent: the viewer sends its text at session start, and
    // sending both ways then would swap the two clipboards.
    func start() {
        guard timer == nil else { return }
        lastText = nil
        seenChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        lastText = nil
    }

    func poll() {
        guard running, pasteboard.changeCount != seenChangeCount else { return }
        seenChangeCount = pasteboard.changeCount
        offer()
    }

    // Text from the viewer. Its own change is marked seen so it is not sent back.
    func apply(_ text: LocalLink.ClipboardText) {
        guard running else { return }
        lastText = text.text
        pasteboard.clearContents()
        pasteboard.setString(text.text, forType: .string)
        seenChangeCount = pasteboard.changeCount
        state.applied += 1
    }

    private func offer() {
        let types = pasteboard.types ?? []
        if types.contains(where: Self.secretTypes.contains) { state.skippedSecret += 1; return }
        guard types.contains(.string) else {
            if !types.isEmpty { state.skippedNonText += 1 }
            return
        }
        // macOS may ask the user before this first read (paste from other apps).
        guard let full = pasteboard.string(forType: .string) else { state.skippedNonText += 1; return }
        // Windows text ends at the first NUL; cut here too so both sides agree.
        let cut = Self.cutAtNUL(full)
        guard !cut.isEmpty else { state.skippedNonText += 1; return }
        guard let text = LocalLink.ClipboardText(cut) else { state.skippedLarge += 1; return }
        guard cut != lastText else { return }
        lastText = cut
        state.sent += 1
        onLocalText?(text)
    }

    static func cutAtNUL(_ text: String) -> String {
        guard let index = text.firstIndex(of: "\0") else { return text }
        return String(text[..<index])
    }
}
